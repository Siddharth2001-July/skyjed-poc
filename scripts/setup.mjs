// One-time setup: creates .env from the template, the JWT key pair the back end signs
// viewer tokens with, and docker-compose.yml for Document Engine + PostgreSQL.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { generateKeyPairSync } from 'node:crypto';

if (!existsSync('.env')) {
	copyFileSync('.env.example', '.env');
	console.log('Created .env from .env.example. Add your licence keys to it.');
}

mkdirSync('keys', { recursive: true });
if (!existsSync('keys/jwt_private.pem')) {
	const { privateKey, publicKey } = generateKeyPairSync('rsa', { modulusLength: 2048 });
	writeFileSync('keys/jwt_private.pem', privateKey.export({ type: 'pkcs1', format: 'pem' }));
	writeFileSync('keys/jwt_public.pem', publicKey.export({ type: 'spki', format: 'pem' }));
	console.log('Generated keys/jwt_private.pem and keys/jwt_public.pem');
}

const publicKey = readFileSync('keys/jwt_public.pem', 'utf8').trim().split('\n').map((l) => `        ${l}`).join('\n');

const compose = `# Generated by scripts/setup.mjs. In production this runs on ECS inside each
# customer's isolated AWS account, with RDS PostgreSQL and S3 asset storage.
services:
  document_engine:
    image: pspdfkit/document-engine:1.19.0
    environment:
      PGUSER: de-user
      PGPASSWORD: password
      PGDATABASE: document-engine
      PGHOST: db
      PGPORT: 5432
      ACTIVATION_KEY: \${DOCUMENT_ENGINE_ACTIVATION_KEY}
      API_AUTH_TOKEN: \${DE_API_TOKEN}
      SECRET_KEY_BASE: skyjed-demo-secret-key-base-skyjed-demo-secret-key-base-0123456789
      JWT_ALGORITHM: RS256
      JWT_PUBLIC_KEY: |
${publicKey}
      DASHBOARD_USERNAME: dashboard
      DASHBOARD_PASSWORD: dashboard-password
      # Production: ASSET_STORAGE_BACKEND: S3, ASSET_STORAGE_S3_BUCKET, ASSET_STORAGE_S3_REGION
    ports:
      - 5001:5000
    depends_on:
      - db
  db:
    image: postgres:16
    environment:
      POSTGRES_USER: de-user
      POSTGRES_PASSWORD: password
      POSTGRES_DB: document-engine
      POSTGRES_INITDB_ARGS: --data-checksums
      PGDATA: /var/lib/postgresql/data/pgdata
    volumes:
      - pgdata:/var/lib/postgresql/data

volumes:
  pgdata:
`;
writeFileSync('docker-compose.yml', compose);
console.log('Wrote docker-compose.yml');
